// Build full deterministic 288-question bank interleaved cleanly across the 8 constructs by tier
function buildFullTieredBank(): TieredAssessmentQuestion[] {
  const all: TieredAssessmentQuestion[] = [];
  let runningIdx = 1;

  // Positions 0..3 => 'quick', 4..17 => 'advanced', 18..35 => 'professional'
  for (let slot = 0; slot < 36; slot++) {
    const minTier: AnalysisTier =
      slot < 4 ? 'quick' : slot < 18 ? 'advanced' : 'professional';

    for (const entry of CONSTRUCT_SEEDS_MAP) {
      const seed = entry.seeds[slot];
      if (!seed) continue;

      all.push({
        id: `tp_${entry.construct}_${slot + 1}`,
        index: runningIdx++,
        construct: entry.construct,
        subscale: seed.subscale,
        facetAr: seed.facetAr,
        facetEn: seed.facetEn,
        format: seed.format || 'likert',
        direction: seed.direction,
        textAr: seed.textAr,
        textEn: seed.textEn,
        scientificReference: entry.ref,
        dimensionExplanationAr: seed.explanationAr,
        dimensionExplanationEn: seed.explanationEn,
        forcedOptions: seed.forcedOptions,
        minTier,
      });
    }
  }

  return all;
}

export const FULL_TIERED_PSYCHOLOGY_BANK: TieredAssessmentQuestion[] = buildFullTieredBank();

export function getQuestionsForAnalysisTier(tier: AnalysisTier): TieredAssessmentQuestion[] {
  if (tier === 'quick') {
    return FULL_TIERED_PSYCHOLOGY_BANK.filter((q) => q.minTier === 'quick');
  }
  if (tier === 'advanced') {
    return FULL_TIERED_PSYCHOLOGY_BANK.filter(
      (q) => q.minTier === 'quick' || q.minTier === 'advanced'
    );
  }
  return FULL_TIERED_PSYCHOLOGY_BANK;
}
