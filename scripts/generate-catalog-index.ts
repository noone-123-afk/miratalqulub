import fs from 'node:fs';
import path from 'node:path';
import { ARTICLES_CATALOG } from '../src/data/articlesData';
import { ACADEMIC_PAPERS_CATALOG } from '../src/data/academicPapersData';
import { NOVELS_CATALOG } from '../src/data/novelsData';
import { PERSONALITY_TESTS_CATALOG } from '../src/data/personalityTestsData';
import { ASSESSMENTS_CATALOG } from '../src/data/psychologySuiteData';
import { INTELLIGENCE_BATTERIES_CATALOG } from '../src/data/intelligenceTestData';
import { ANALYSIS_TIERS_CATALOG } from '../src/data/tieredPsychologyBank';

const OUTPUT_PATH = path.resolve('src/data/catalogMetadataIndex.ts');

function main() {
  const articlesMeta = ARTICLES_CATALOG.map((art) => ({
    id: art.id,
    title: art.title,
    titleEn: art.titleEn,
    summary: art.summary,
    summaryEn: art.summaryEn,
    category: art.category,
    categoryLabelAr: art.categoryLabelAr,
    categoryLabelEn: art.categoryLabelEn,
    readTime: art.readTime,
    readTimeEn: art.readTimeEn,
    publishDate: art.publishDate || '2026-01-01',
    icon: art.icon || '📖',
    scientificFramework: art.scientificFramework,
    keyTakeaways: art.keyTakeaways,
  }));

  const academicMeta = ACADEMIC_PAPERS_CATALOG.map((paper) => ({
    id: paper.id,
    titleAr: paper.titleAr,
    titleEn: paper.titleEn,
    abstractAr: paper.abstractAr,
    abstractEn: paper.abstractEn,
    category: paper.category,
    categoryLabelAr: paper.categoryLabelAr,
    categoryLabelEn: paper.categoryLabelEn,
    readTimeAr: paper.readTimeAr,
    readTimeEn: paper.readTimeEn,
    publishDate: paper.publishDate || '2026-01-01',
    icon: paper.icon || '🎓',
    keywordsAr: paper.keywordsAr,
    keywordsEn: paper.keywordsEn,
  }));

  const novelsMeta = NOVELS_CATALOG.map((nv) => ({
    id: nv.id,
    titleAr: nv.titleAr,
    titleEn: nv.titleEn || nv.titleAr,
    genre: nv.genre,
    genreLabelAr: nv.genreLabelAr,
    genreLabelEn: nv.genreLabelEn || nv.genre,
    synopsisAr: nv.synopsisAr,
    synopsisEn: nv.synopsisEn || nv.synopsisAr,
    forensicThemeAr: nv.forensicThemeAr,
    psychologicalFocusAr: nv.psychologicalFocusAr,
    estimatedReadingTime: nv.estimatedReadingTime,
    totalChapters: nv.totalChapters,
  }));

  const personalityTestsMeta = PERSONALITY_TESTS_CATALOG.filter(
    (t) =>
      t.id === 'mbti_16types' ||
      t.id === 'big_five_ocean' ||
      t.id === 'existential_fatigue'
  ).map((t) => ({
    id: t.id,
    titleAr: t.titleAr,
    titleEn: t.titleEn,
    subtitleAr: t.subtitleAr,
    subtitleEn: t.subtitleEn,
    shortDescriptionAr: t.shortDescriptionAr,
    shortDescriptionEn: t.shortDescriptionEn,
  }));

  const analysisTiersMeta = ANALYSIS_TIERS_CATALOG.slice(0, 2).map((tier) => ({
    id: tier.id,
    titleAr: tier.titleAr,
    titleEn: tier.titleEn,
    descriptionAr: tier.descriptionAr,
    descriptionEn: tier.descriptionEn,
  }));

  const assessmentsMeta = ASSESSMENTS_CATALOG.map((a) => ({
    id: a.id,
    titleAr: a.titleAr,
    titleEn: a.titleEn,
    categoryTitleAr: a.categoryTitleAr,
    shortDesc: a.shortDesc,
    scientificReference: a.scientificReference,
  }));

  const intelligenceBatteriesMeta = INTELLIGENCE_BATTERIES_CATALOG.map((b) => ({
    id: b.id,
    titleAr: b.titleAr,
    titleEn: b.titleEn,
    descriptionAr: b.descriptionAr,
    scientificScaleName: b.scientificScaleName,
    icon: b.icon,
  }));

  const fileContent = `// AUTO-GENERATED BY scripts/generate-catalog-index.ts — DO NOT EDIT MANUALLY
// Lightweight metadata index used by recommendationEngine so pages never eagerly bundle 5+ MB of full-text prose & quiz banks.
import type { NovelGenre } from './novelsData';
import type { AssessmentType } from './psychologySuiteData';
import type { IntelligenceBatteryType } from './intelligenceTestData';

export interface IndexedArticleMeta {
  id: string;
  title: string;
  titleEn: string;
  summary: string;
  summaryEn: string;
  category: string;
  categoryLabelAr: string;
  categoryLabelEn: string;
  readTime: string;
  readTimeEn: string;
  publishDate: string;
  icon: string;
  scientificFramework: string;
  keyTakeaways: string[];
}

export interface IndexedAcademicMeta {
  id: string;
  titleAr: string;
  titleEn: string;
  abstractAr: string;
  abstractEn: string;
  category: string;
  categoryLabelAr: string;
  categoryLabelEn: string;
  readTimeAr: string;
  readTimeEn: string;
  publishDate: string;
  icon: string;
  keywordsAr: string[];
  keywordsEn: string[];
}

export interface IndexedNovelMeta {
  id: string;
  titleAr: string;
  titleEn: string;
  genre: NovelGenre;
  genreLabelAr: string;
  genreLabelEn: string;
  synopsisAr: string;
  synopsisEn: string;
  forensicThemeAr: string;
  psychologicalFocusAr: string;
  estimatedReadingTime: string;
  totalChapters: number;
}

export interface IndexedPersonalityTestMeta {
  id: string;
  titleAr: string;
  titleEn: string;
  subtitleAr: string;
  subtitleEn: string;
  shortDescriptionAr: string;
  shortDescriptionEn: string;
}

export interface IndexedAnalysisTierMeta {
  id: string;
  titleAr: string;
  titleEn: string;
  descriptionAr: string;
  descriptionEn: string;
}

export interface IndexedAssessmentMeta {
  id: AssessmentType;
  titleAr: string;
  titleEn: string;
  categoryTitleAr: string;
  shortDesc: string;
  scientificReference: string;
}

export interface IndexedIntelligenceBatteryMeta {
  id: IntelligenceBatteryType;
  titleAr: string;
  titleEn: string;
  descriptionAr: string;
  scientificScaleName: string;
  icon: string;
}

export const INDEX_ARTICLES_META: IndexedArticleMeta[] = ${JSON.stringify(articlesMeta, null, 2)};

export const INDEX_ACADEMIC_META: IndexedAcademicMeta[] = ${JSON.stringify(academicMeta, null, 2)};

export const INDEX_NOVELS_META: IndexedNovelMeta[] = ${JSON.stringify(novelsMeta, null, 2)};

export const INDEX_PERSONALITY_TESTS_META: IndexedPersonalityTestMeta[] = ${JSON.stringify(personalityTestsMeta, null, 2)};

export const INDEX_ANALYSIS_TIERS_META: IndexedAnalysisTierMeta[] = ${JSON.stringify(analysisTiersMeta, null, 2)};

export const INDEX_ASSESSMENTS_META: IndexedAssessmentMeta[] = ${JSON.stringify(assessmentsMeta, null, 2)};

export const INDEX_INTELLIGENCE_BATTERIES_META: IndexedIntelligenceBatteryMeta[] = ${JSON.stringify(intelligenceBatteriesMeta, null, 2)};
`;

  fs.writeFileSync(OUTPUT_PATH, fileContent, 'utf-8');
  const bytes = Buffer.byteLength(fileContent, 'utf-8');
  console.log(
    `[catalog-index] Wrote ${OUTPUT_PATH} (${(bytes / 1024).toFixed(1)} KB; ${articlesMeta.length} articles, ${academicMeta.length} papers, ${novelsMeta.length} novels, ${assessmentsMeta.length} assessments).`
  );
}

main();
